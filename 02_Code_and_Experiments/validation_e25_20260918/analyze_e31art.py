#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""E31 ART analysis: the five-arm long-replacement sweep.

Reads results/main/long_e31art_{same,grow}.jsonl (C1 / C2 / C3 / E31 / ART, 5
processes x 3 datasets x 5 repetitions x 4 checkpoints) and writes
results/main/e31art_analysis.txt (UTF-8).

Two things this file exists to answer, neither of which the four-arm file can:
  1. ART's standing under long-run replacement, measured in the SAME process and the
     SAME repetition as the four Index arms -- the round's plan asked for it.
  2. Whether the four Index arms re-measured here agree with the four-arm run in
     long_e31_{same,grow}.jsonl. The arm order is rotated here and not there, so the
     agreement is a check on the rotation, not an assumption.

ART convention: overflow / compactions / memory / blocks / ov_bytes are written as 0
and mean NOT APPLICABLE -- libart exposes no overflow, compaction or byte accounting
through this adapter. Every table that prints them either omits the ART arm or marks
it. query_acc and query_ms are real for ART.

Aggregation: a cell's per-process value is the median of the within-repetition paired
ratios; the headline is the median of the per-process values and the direction count is
how many of the 5 processes agree with it. The pooled median over every
process-repetition ratio is printed beside it, because that is what the draft report
printed for the four-arm file.
"""
import json, os, statistics as st

DIR = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(DIR, "results", "main", "e31art_analysis.txt")
MODES = ("same", "grow")
KINDS = ("mixed", "skew", "tranco")
FRACS = (0.25, 0.50, 1.00, 2.00)
TAGS = ("P1", "P2", "P3", "P4", "P5")
INDEX_ARMS = ("C1", "C2", "C3", "E31")
ALL_ARMS = INDEX_ARMS + ("ART",)
MIB = 1024.0 * 1024.0


def load(path):
    return [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]


def main():
    out = open(OUT, "w", encoding="utf-8")
    w = out.write
    w("# E31 ART analysis (generated by analyze_e31art.py)\n")
    w("# five arms: C1 / C2=frozen / C3=frozen+compact_repack_budget / E31=frozen+subblock_reclaim / ART=libart\n")

    for mode in MODES:
        p5 = os.path.join(DIR, "results", "main", "long_e31art_%s.jsonl" % mode)
        p4 = os.path.join(DIR, "results", "main", "long_e31_%s.jsonl" % mode)
        rows5 = load(p5)
        rows4 = load(p4)
        reps5 = sorted({r["rep"] for r in rows5})
        reps4 = sorted({r["rep"] for r in rows4})
        idx5 = {(r["kind"], r["rep"], r["arm"], r["run_tag"], r["frac"]): r for r in rows5}
        idx4 = {(r["kind"], r["rep"], r["arm"], r["run_tag"], r["frac"]): r for r in rows4}

        w("\n%s\n## mode = %s\n%s\n" % ("#" * 78, mode, "#" * 78))
        w("\n-- bookkeeping --\n")
        w("  five-arm file: %d records, reps %s\n" % (len(rows5), reps5))
        w("  four-arm file: %d records, reps %s\n" % (len(rows4), reps4))
        missing = [(k, f, a, t, rep) for k in KINDS for f in FRACS for a in ALL_ARMS
                   for t in TAGS for rep in reps5
                   if (k, rep, a, t, f) not in idx5]
        expect = len(KINDS) * len(FRACS) * len(ALL_ARMS) * len(TAGS) * len(reps5)
        w("  expected %d for 5 procs x 3 data x %d reps x %d arms x 4 checkpoints; missing: %s\n"
          % (expect, len(reps5), len(ALL_ARMS), missing if missing else "none"))

        w("\n-- integrity: query_acc across the five arms of one cell --\n")
        bad = []
        for k in KINDS:
            for f in FRACS:
                for t in TAGS:
                    for rep in reps5:
                        v = {a: idx5[(k, rep, a, t, f)]["query_acc"] for a in ALL_ARMS
                             if (k, rep, a, t, f) in idx5}
                        if len(set(v.values())) > 1:
                            bad.append((k, f, t, rep, v))
        w("  cells where the arms disagree on the query answer sum: %d\n" % len(bad))
        for b in bad[:12]:
            w("    %s\n" % (b,))

        # ---- ratios ---------------------------------------------------------
        for num, den, label in (("E31", "C2", "E31 / C2 (frozen)"),
                                ("ART", "C2", "ART / C2 (frozen)"),
                                ("E31", "ART", "E31 / ART"),
                                ("C2", "ART", "C2 (frozen) / ART"),
                                ("C3", "C2", "C3 / C2 (frozen)"),
                                ("C2", "C1", "C2 / C1")):
            w("\n-- maintenance ratio, %s --\n" % label)
            w("  %-7s %5s %9s %9s %9s %6s   %s\n"
              % ("data", "frac", "procMed", "pooled", "max/min", "dir", "per-process medians"))
            for k in KINDS:
                for f in FRACS:
                    per, pooled = [], []
                    for t in TAGS:
                        rr = []
                        for rep in reps5:
                            a = idx5.get((k, rep, num, t, f))
                            b = idx5.get((k, rep, den, t, f))
                            if a and b and b["cum_ms"]:
                                rr.append(a["cum_ms"] / b["cum_ms"])
                        if rr:
                            per.append(st.median(rr))
                            pooled.extend(rr)
                    if not per:
                        continue
                    w("  %-7s %5.2f %9.3f %9.3f %9.3f %4d/%d   %s\n"
                      % (k, f, st.median(per), st.median(pooled), max(per) / min(per),
                         sum(1 for v in per if v < 1.0), len(per),
                         " ".join("%.3f" % v for v in per)))

        # ---- consistency against the four-arm run ---------------------------
        w("\n-- consistency: same statistic from the four-arm run (3 reps, fixed order) --\n")
        w("  %-7s %5s %9s %9s %9s %9s\n"
          % ("data", "frac", "E31/C2-5arm", "E31/C2-4arm", "C2/C1-5arm", "C2/C1-4arm"))
        for k in KINDS:
            for f in FRACS:
                def stat(idx, reps, num, den):
                    per = []
                    for t in TAGS:
                        rr = [idx[(k, rep, num, t, f)]["cum_ms"] / idx[(k, rep, den, t, f)]["cum_ms"]
                              for rep in reps
                              if (k, rep, num, t, f) in idx and (k, rep, den, t, f) in idx]
                        if rr:
                            per.append(st.median(rr))
                    return st.median(per) if per else float("nan")
                w("  %-7s %5.2f %9.3f %9.3f %9.3f %9.3f\n"
                  % (k, f, stat(idx5, reps5, "E31", "C2"), stat(idx4, reps4, "E31", "C2"),
                     stat(idx5, reps5, "C2", "C1"), stat(idx4, reps4, "C2", "C1")))

        # ---- structural (Index arms only) -----------------------------------
        w("\n-- structural, INDEX ARMS ONLY (median over the process-repetition cells) --\n")
        w("  ART is excluded: 0 would mean 'not applicable', not 'zero'. --\n")
        w("  %-7s %5s %-4s %10s %12s %12s %12s\n"
          % ("data", "frac", "arm", "overflow", "compactions", "memory_B", "memory_MiB"))
        for k in KINDS:
            for f in FRACS:
                for a in INDEX_ARMS:
                    g = [idx5[(k, rep, a, t, f)] for t in TAGS for rep in reps5
                         if (k, rep, a, t, f) in idx5]
                    if not g:
                        continue
                    med = lambda key: st.median([x[key] for x in g])
                    w("  %-7s %5.2f %-4s %10.0f %12.0f %12.0f %12.2f\n"
                      % (k, f, a, med("overflow"), med("compactions"), med("memory"),
                         med("memory") / MIB))
            w("\n")

        # ---- query side, all five arms --------------------------------------
        w("-- query side: query_ms per checkpoint (median over the process-repetition cells) --\n")
        w("  %-7s %5s %9s %9s %9s %9s %9s   %9s %9s %6s\n"
          % ("data", "frac", "C1", "C2", "C3", "E31", "ART", "E31/C2", "E31/ART", "dir"))
        for k in KINDS:
            for f in FRACS:
                med = {}
                for a in ALL_ARMS:
                    v = [idx5[(k, rep, a, t, f)]["query_ms"] for t in TAGS for rep in reps5
                         if (k, rep, a, t, f) in idx5]
                    med[a] = st.median(v) if v else float("nan")
                per = [st.median([idx5[(k, rep, "E31", t, f)]["query_ms"] /
                                  idx5[(k, rep, "C2", t, f)]["query_ms"] for rep in reps5])
                       for t in TAGS]
                per_art = [st.median([idx5[(k, rep, "E31", t, f)]["query_ms"] /
                                      idx5[(k, rep, "ART", t, f)]["query_ms"] for rep in reps5])
                           for t in TAGS]
                w("  %-7s %5.2f %9.3f %9.3f %9.3f %9.3f %9.3f   %9.3f %9.3f %4d/%d\n"
                  % (k, f, med["C1"], med["C2"], med["C3"], med["E31"], med["ART"],
                     st.median(per), st.median(per_art),
                     sum(1 for v in per if v < 1.0), len(per)))

        # ---- absolute times, so a ratio can be read against a magnitude ------
        w("\n-- absolute cum_ms, median over the process-repetition cells (all five arms) --\n")
        w("  %-7s %5s %10s %10s %10s %10s %10s\n"
          % ("data", "frac", "C1", "C2", "C3", "E31", "ART"))
        for k in KINDS:
            for f in FRACS:
                med = {}
                for a in ALL_ARMS:
                    v = [idx5[(k, rep, a, t, f)]["cum_ms"] for t in TAGS for rep in reps5
                         if (k, rep, a, t, f) in idx5]
                    med[a] = st.median(v) if v else float("nan")
                w("  %-7s %5.2f %10.2f %10.2f %10.2f %10.2f %10.2f\n"
                  % (k, f, med["C1"], med["C2"], med["C3"], med["E31"], med["ART"]))

        # ---- payback vs ART -------------------------------------------------
        w("\n-- payback against ART: maintenance delta and per-batch query delta --\n")
        w("  %-7s %5s %14s %14s %14s %14s\n"
          % ("data", "frac", "maint E31-ART", "maint C2-ART", "query E31-ART", "query C2-ART"))
        for k in KINDS:
            for f in FRACS:
                m = lambda a: st.median([idx5[(k, rep, a, t, f)]["cum_ms"]
                                         for t in TAGS for rep in reps5])
                q = lambda a: st.median([idx5[(k, rep, a, t, f)]["query_ms"]
                                         for t in TAGS for rep in reps5])
                w("  %-7s %5.2f %14.2f %14.2f %14.3f %14.3f\n"
                  % (k, f, m("E31") - m("ART"), m("C2") - m("ART"),
                     q("E31") - q("ART"), q("C2") - q("ART")))

    out.close()
    print("wrote", OUT)


if __name__ == "__main__":
    main()
